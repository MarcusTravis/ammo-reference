// Pre-render each chart's table rows into the HTML so the data is readable
// without JavaScript (search engines, AI crawlers, no-JS readers).
// The page's own render() still runs on load and replaces these rows, so
// filters and sorting work exactly as before.
//
// Usage (repo root):  node tools/render-static-rows.mjs
// Needs jsdom:  npm i --no-save jsdom   (or set JSDOM_DIR to a folder that has it)
// Re-run after ANY edit to a chart's DATA / TWIST / BC / DIM / PLAT, or to scroll-hint.js's M map.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const req = createRequire(path.join(process.env.JSDOM_DIR || root, "noop.js"));
const { JSDOM, VirtualConsole } = req("jsdom");
const hint = fs.readFileSync(path.join(root, "scroll-hint.js"), "utf8");
const TB = /(<tbody id="rows">)[\s\S]*?(<\/tbody>)/;
const CNT = /(<[a-z]+[^>]*id="count"[^>]*>)[^<]*(<\/[a-z]+>)/;
let changed = 0, total = 0;
for (const f of fs.readdirSync(root).filter(f => f.endsWith(".html")).sort()) {
  const file = path.join(root, f);
  const html = fs.readFileSync(file, "utf8");
  if (!TB.test(html)) continue;
  const blank = html.replace(TB, "$1$2").replace(/<script src="scroll-hint\.js"><\/script>/, "");
  const vc = new VirtualConsole();
  const errs = [];
  vc.on("jsdomError", e => errs.push(e.message));
  const dom = new JSDOM(blank, { runScripts: "dangerously", url: pathToFileURL(file).href, virtualConsole: vc, pretendToBeVisual: true });
  const w = dom.window;
  w.eval(hint);
  const tb = w.document.getElementById("rows");
  const n = tb.querySelectorAll("tr").length;
  if (errs.length || !n) { console.error(`${f}: FAILED (${n} rows) ${errs.join("; ")}`); process.exitCode = 1; continue; }
  const rows = "<!-- static rows: generated by tools/render-static-rows.mjs; render() replaces them -->" + tb.innerHTML;
  let out = html.replace(TB, (m, a, b) => a + rows + b);
  const cnt = w.document.getElementById("count");
  if (cnt && CNT.test(out)) out = out.replace(CNT, (m, a, b) => a + cnt.textContent + b);
  total += n;
  if (out !== html) { fs.writeFileSync(file, out); changed++; }
  console.log(`${f}: ${n} rows`);
  w.close();
}
console.log(`${total} rows total; ${changed} file(s) updated`);
